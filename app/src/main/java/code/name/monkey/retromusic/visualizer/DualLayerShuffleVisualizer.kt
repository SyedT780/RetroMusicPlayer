package code.name.monkey.retromusic.visualizer

import code.name.monkey.retromusic.extensions.computeInvariantRanks
import code.name.monkey.retromusic.model.Song
import kotlin.math.PI
import kotlin.math.cos
import kotlin.math.sin

/**
 * Immutable track descriptor containing stable identity.
 */
data class TrackItem(
    val id: String,
    val invariantId: Int, // Stable index in [0, N-1]
    val title: String,
    val artist: String
)

data class PointF(
    val x: Float,
    val y: Float
)

data class VisualizerNode(
    val slot: Int,
    val trackId: String,
    val position: PointF,
    val isCollisionWithPrevious: Boolean
) {
    val isCollision: Boolean get() = isCollisionWithPrevious
    val coordinate: PointF get() = position
}

data class DualLayerFrame(
    val baselinePoints: List<PointF>,    // Frozen original shuffle path
    val livePoints: List<PointF>,        // Active queue path (deflects on manual edits)
    val liveNodes: List<VisualizerNode>, // Track nodes with collision flags
    val isClosedLoop: Boolean            // True if queue is an intact permutation of library
)

class DualLayerShuffleVisualizer(
    private var totalLibraryN: Int = 1,
    private val slotToleranceDelta: Int = 0 // 0 = exact slot match; 1 = adjacent slot match
) {
    // 1. Immutable Baseline: The initial plan generated by the engine
    private var baselineQueue: List<TrackItem> = emptyList()
    private var baselinePoints: List<PointF> = emptyList()

    // 2. Previous Finalized Session: Strictly truncated to tracks actually played
    private var previousFinalizedRun: List<Int> = emptyList()

    // 3. Playback Cursor: Index of the track currently playing
    private var currentPlaybackCursor: Int = 0

    @Synchronized
    fun resetHistory() {
        baselineQueue = emptyList()
        baselinePoints = emptyList()
        previousFinalizedRun = emptyList()
        currentPlaybackCursor = 0
    }

    /**
     * Triggered when a new shuffle is started.
     * Truncates the prior session up to currentPlaybackCursor, discards unplayed
     * tail items, and freezes the new baseline trajectory.
     */
    @Synchronized
    fun onNewShuffleTriggered(newQueue: List<TrackItem>, startingIndex: Int = 0) {
        if (newQueue.isNotEmpty()) {
            totalLibraryN = maxOf(totalLibraryN, newQueue.size)
        }

        // Step 1: Finalize previous run by truncating unplayed remainder
        if (baselineQueue.isNotEmpty()) {
            val finalizedLength = (currentPlaybackCursor + 1).coerceAtMost(baselineQueue.size)
            previousFinalizedRun = baselineQueue.subList(0, finalizedLength).map { it.invariantId }
        }

        // Step 2: Establish new immutable baseline
        baselineQueue = ArrayList(newQueue)
        currentPlaybackCursor = startingIndex
        baselinePoints = computeCoordinateWalk(baselineQueue)
    }

    /**
     * Triggered by the media player service when track playback advances.
     */
    @Synchronized
    fun onPlaybackCursorChanged(newCursorIndex: Int) {
        this.currentPlaybackCursor = newCursorIndex
    }

    /**
     * Real-time recalculation triggered on every queue mutation:
     * - Drag-and-drop reordering
     * - "Play Next" insertions
     * - Deleting tracks or albums
     *
     * Runs in O(M) time without modifying baselinePoints.
     */
    @Synchronized
    fun computeLiveFrame(currentQueue: List<TrackItem>): DualLayerFrame {
        val nodeCount = currentQueue.size
        if (nodeCount == 0) {
            return DualLayerFrame(
                baselinePoints = baselinePoints,
                livePoints = listOf(PointF(0f, 0f)),
                liveNodes = emptyList(),
                isClosedLoop = true
            )
        }

        val livePoints = ArrayList<PointF>(nodeCount + 1)
        val liveNodes = ArrayList<VisualizerNode>(nodeCount)

        var curX = 0.0f
        var curY = 0.0f
        livePoints.add(PointF(curX, curY))

        val effectiveN = maxOf(1, totalLibraryN)
        val angleStep = (2.0 * PI) / effectiveN.toDouble()
        val prevRunSize = previousFinalizedRun.size

        for (slot in 0 until nodeCount) {
            val track = currentQueue[slot]
            val invId = track.invariantId

            // Advance coordinate along unit vector defined by invariant track ID
            val theta = invId * angleStep
            curX += cos(theta).toFloat()
            curY += sin(theta).toFloat()
            val nodePos = PointF(curX, curY)
            livePoints.add(nodePos)

            // Overlap check strictly against immediate previous finalized run
            var isCollision = false
            if (prevRunSize > 0) {
                val startCheck = (slot - slotToleranceDelta).coerceAtLeast(0)
                val endCheck = (slot + slotToleranceDelta).coerceAtMost(prevRunSize - 1)
                for (checkSlot in startCheck..endCheck) {
                    if (previousFinalizedRun[checkSlot] == invId) {
                        isCollision = true
                        break
                    }
                }
            }

            liveNodes.add(
                VisualizerNode(
                    slot = slot,
                    trackId = track.id,
                    position = nodePos,
                    isCollisionWithPrevious = isCollision
                )
            )
        }

        // Loop closure validation: returns to (0, 0) only if queue is complete and unmutated
        val isClosed = (curX * curX + curY * curY) < 0.01f

        return DualLayerFrame(
            baselinePoints = baselinePoints,
            livePoints = livePoints,
            liveNodes = liveNodes,
            isClosedLoop = isClosed
        )
    }

    private fun computeCoordinateWalk(queue: List<TrackItem>): List<PointF> {
        val points = ArrayList<PointF>(queue.size + 1)
        var x = 0.0f
        var y = 0.0f
        points.add(PointF(x, y))

        val effectiveN = maxOf(1, totalLibraryN)
        val angleStep = (2.0 * PI) / effectiveN.toDouble()
        for (track in queue) {
            val theta = track.invariantId * angleStep
            x += cos(theta).toFloat()
            y += sin(theta).toFloat()
            points.add(PointF(x, y))
        }
        return points
    }

    companion object {
        fun List<Song>.toTrackItems(): List<TrackItem> {
            if (isEmpty()) return emptyList()
            val rankMap = computeInvariantRanks()
            return map { song ->
                TrackItem(
                    id = song.id.toString(),
                    invariantId = rankMap[song.id] ?: 0,
                    title = song.title,
                    artist = song.artistName
                )
            }
        }
    }
}
